#[test]
fn twocell_anchor_edit_as_collapses_to_default() {
    // editAs=TwoCell and editAs=None both map to ClientAnchor flag=0
    // (move+resize with cells) — the byte layout cannot distinguish
    // them, and they mean the same thing. The reader normalises
    // flag=0 to None so the model default round-trips exactly.
    let mut wb = Workbook::new();
    let ws = wb.worksheet_mut(0).unwrap();
    ws.add_drawing(test_image("Picture 1", 1, 2).with_anchor(DrawingAnchor::TwoCell {
        from: CellMarker {
            col: 1,
            col_offset_emu: 0,
            row: 2,
            row_offset_emu: 0,
        },
        to: CellMarker {
            col: 4,
            col_offset_emu: 0,
            row: 7,
            row_offset_emu: 0,
        },
        edit_as: Some(EditAs::TwoCell),
    }));

    let parsed = write_then_read(&wb);
    let images = images_of(parsed.worksheet(0).unwrap());
    if let DrawingAnchor::TwoCell { edit_as, .. } = &images[0].object.anchor {
        assert_eq!(*edit_as, None);
    } else {
        panic!("expected TwoCell");
    }
}

#[test]
fn onecell_anchor_round_trips_with_visual_area_preserved() {
    // OneCell input: from cell + width/height in EMU.
    // Writer encodes this as a TwoCell-style ClientAnchor with
    // flag=2 (move only). Reader maps flag=2 back to TwoCell with
    // editAs=OneCell. The variant tag is lost but the visual area
    // is preserved.
    const COL_EMU: i64 = 609_600;
    const ROW_EMU: i64 = 190_500;
    let mut wb = Workbook::new();
    let ws = wb.worksheet_mut(0).unwrap();
    ws.add_drawing(test_image("Picture 1", 0, 0).with_anchor(DrawingAnchor::OneCell {
        from: CellMarker {
            col: 2,
            col_offset_emu: 0,
            row: 3,
            row_offset_emu: 0,
        },
        // Exactly 3 columns × 2 rows worth of default cells.
        width_emu: 3 * COL_EMU,
        height_emu: 2 * ROW_EMU,
    }));

    let parsed = write_then_read(&wb);
    let images = images_of(parsed.worksheet(0).unwrap());
    let img = &images[0];
    match &img.object.anchor {
        DrawingAnchor::TwoCell {
            from,
            to,
            edit_as,
        } => {
            assert_eq!(from.col, 2);
            assert_eq!(from.row, 3);
            assert_eq!(to.col, 5, "OneCell width must extend by 3 cols");
            assert_eq!(to.row, 5, "OneCell height must extend by 2 rows");
            assert_eq!(*edit_as, Some(EditAs::OneCell));
        }
        other => panic!("expected TwoCell with editAs=OneCell, got {other:?}"),
    }
    assert_eq!(img.payload.width_emu, 3 * COL_EMU);
    assert_eq!(img.payload.height_emu, 2 * ROW_EMU);
}

