#[test]
fn large_images_round_trip_via_continue_records() {
    // Realistic images exceed the 8224-byte BIFF record body cap, so
    // MSODRAWINGGROUP (which carries every blip's bytes) must be split
    // across CONTINUE records. 20 KB covers the >8224 case; 80 KB also
    // covers bodies whose length cannot be represented in the record's
    // u16 size field at all.
    for size in [20_000usize, 80_000] {
        let mut data = TEST_PNG_1X1.to_vec();
        data.resize(size, 0xAB);

        let mut wb = Workbook::new();
        let ws = wb.worksheet_mut(0).unwrap();
        ws.add_drawing(test_image_with_format("Big", 1, 1, ImageFormat::Png, &data));

        let parsed = write_then_read(&wb);
        let images = images_of(parsed.worksheet(0).unwrap());
        assert_eq!(images.len(), 1, "{size}-byte image must survive round-trip");
        assert_eq!(
            images[0].payload.data(),
            &data[..],
            "{size}-byte image bytes must survive CONTINUE splitting"
        );
    }
}

#[test]
fn single_picture_round_trips() {
    let mut wb = Workbook::new();
    let ws = wb.worksheet_mut(0).unwrap();
    ws.set_cell_value("A1", "anchor").expect("A1");
    ws.add_drawing(test_image("Picture 1", 2, 3));

    let parsed = write_then_read(&wb);
    let images = images_of(parsed.worksheet(0).unwrap());
    assert_eq!(images.len(), 1, "picture must survive round-trip");

    let img = &images[0];
    assert_eq!(img.payload.format, ImageFormat::Png);
    assert_eq!(
        img.payload.data, TEST_PNG_1X1,
        "PNG bytes must round-trip verbatim"
    );
    assert_eq!(img.object.meta.name.as_deref(), Some("Picture 1"));
    if let DrawingAnchor::TwoCell { from, to, .. } = &img.object.anchor {
        assert_eq!(from.col, 2);
        assert_eq!(from.row, 3);
        assert_eq!(to.col, 5);
        assert_eq!(to.row, 8);
    } else {
        panic!("expected TwoCell anchor, got {:?}", img.object.anchor);
    }
}

#[test]
fn xls_top_level_width_emu_does_not_survive_user_value() {
    // **Documented limitation.** EmbeddedImage.width_emu /
    // height_emu (the top-level fields, not the OneCell/Absolute
    // variant's inner width_emu/height_emu) are NOT preserved
    // through the XLS writer. The writer only encodes the anchor
    // cells and within-cell EMU offsets; the reader synthesises
    // top-level width_emu/height_emu from the anchor cell range
    // using default cell sizes (609,600 EMU per column, 190,500
    // per row).
    //
    // A user who sets a top-level width_emu = 7_500_000 (arbitrary
    // value) with a TwoCell anchor spanning 3 cols × 2 rows of
    // default cells will see width_emu = 3 × 609,600 = 1_828_800
    // on round-trip — their value is silently replaced.
    let mut wb = Workbook::new();
    let ws = wb.worksheet_mut(0).unwrap();
    let mut payload = test_payload(ImageFormat::Png, TEST_PNG_1X1);
    payload.width_emu = 7_500_000; // user-supplied non-default value
    payload.height_emu = 4_500_000;
    let anchor = DrawingAnchor::TwoCell {
        from: CellMarker {
            col: 0,
            col_offset_emu: 0,
            row: 0,
            row_offset_emu: 0,
        },
        to: CellMarker {
            col: 3,
            col_offset_emu: 0,
            row: 2,
            row_offset_emu: 0,
        },
        edit_as: None,
    };
    ws.add_drawing(
        DrawingObject::image(payload)
            .with_anchor(anchor)
            .with_name("Pic"),
    );

    let parsed = write_then_read(&wb);
    let images = images_of(parsed.worksheet(0).unwrap());
    let out = images[0].payload;

    // The user's 7,500,000 / 4,500,000 are NOT preserved. Instead,
    // width_emu becomes 3 cols × 609,600 = 1,828,800 and
    // height_emu becomes 2 rows × 190,500 = 381,000.
    assert_eq!(
        out.width_emu, 1_828_800,
        "top-level width_emu is overwritten by synthesised value (3 cols × default cell width)"
    );
    assert_eq!(
        out.height_emu, 381_000,
        "top-level height_emu is overwritten by synthesised value (2 rows × default row height)"
    );
    assert_ne!(
        out.width_emu, 7_500_000,
        "the user's input width_emu is silently lost — documented limitation"
    );
}

