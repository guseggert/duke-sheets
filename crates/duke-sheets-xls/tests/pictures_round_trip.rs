fn write_then_read(wb: &Workbook) -> Workbook {
    let bytes = XlsWriter::write_to_bytes(wb).expect("serialize");
    XlsReader::read(Cursor::new(&bytes)).expect("read back")
}

fn images_of(ws: &Worksheet) -> Vec<Drawn<'_, EmbeddedImage>> {
    ws.images().collect()
}

fn test_anchor(from_col: u16, from_row: u32) -> DrawingAnchor {
    DrawingAnchor::TwoCell {
        from: CellMarker {
            col: from_col,
            col_offset_emu: 0,
            row: from_row,
            row_offset_emu: 0,
        },
        to: CellMarker {
            col: from_col + 3,
            col_offset_emu: 0,
            row: from_row + 5,
            row_offset_emu: 0,
        },
        edit_as: None,
    }
}

fn test_payload(format: ImageFormat, data: &[u8]) -> EmbeddedImage {
    EmbeddedImage {
        format,
        media_path: String::new(),
        svg_media_path: None,
        width_emu: 1_000_000,
        height_emu: 1_000_000,
        rotation: None,
        flip_h: false,
        flip_v: false,
        data: data.to_vec(),
        svg_data: None,
    }
}

fn test_image(name: &str, from_col: u16, from_row: u32) -> DrawingObject {
    test_image_with_format(name, from_col, from_row, ImageFormat::Png, TEST_PNG_1X1)
}

fn test_image_with_format(
    name: &str,
    from_col: u16,
    from_row: u32,
    format: ImageFormat,
    data: &[u8],
) -> DrawingObject {
    DrawingObject::image(test_payload(format, data))
        .with_anchor(test_anchor(from_col, from_row))
        .with_name(name)
}

